function AppInner() {
  const [activePath, setActivePath] = useState<string | undefined>(undefined);
  const [leftPath, setLeftPath] = useState<string | undefined>(undefined);
  const [rightPath, setRightPath] = useState<string | undefined>(undefined);
  const [rootPath, setRootPath] = useState<string | undefined>(undefined);
  const [dropOverlay, setDropOverlay] = useState(false);
  const dropCounter = useRef(0);
  const { settings, updateSetting } = useSettings();

  // ── CLI arg handling (Tauri only) ────────────────────────────────────
  useEffect(() => {
    if (!isTauri) return;
    getLaunchArgs().then(async (args) => {
      if (args.length === 0) return;
      // First positional arg as directory or left file
      const first = args[0];
      const firstIsDir = await pathIsDir(first);
      if (firstIsDir) {
        setRootPath(first);
        return;
      }
      // Two file args → left/right compare
      if (args.length >= 2) {
        setLeftPath(first);
        setRightPath(args[1]);
      } else {
        // Single file arg → open as right (preview)
        setRightPath(first);
      }
    }).catch(() => {
      // get_launch_args unavailable (e.g. Vite dev) — silently ignore
    });
  }, []);

  // ── Drag-and-drop handling (Tauri only) ──────────────────────────────
  useEffect(() => {
    if (!isTauri) return;

    const unlistenDragEnter = listen<string[]>('tauri://drag-enter', () => {
      dropCounter.current++;
      setDropOverlay(true);
    });

    const unlistenDragLeave = listen('tauri://drag-leave', () => {
      dropCounter.current--;
      if (dropCounter.current <= 0) {
        dropCounter.current = 0;
        setDropOverlay(false);
      }
    });

    const unlistenDragDrop = listen<string[]>('tauri://drag-drop', async (event) => {
      dropCounter.current = 0;
      setDropOverlay(false);

      const paths = event.payload;
      if (paths.length === 0) return;

      // Single directory → scan it
      if (paths.length === 1) {
        const isDir = await pathIsDir(paths[0]);
        if (isDir) {
          setRootPath(paths[0]);
          return;
        }
        // Single file → open as right (preview)
        setRightPath(paths[0]);
        setActivePath(undefined);
        return;
      }

      // Multiple files → use first two as left/right
      setLeftPath(paths[0]);
      setRightPath(paths[1]);
      setActivePath(undefined);
    });

    return () => {
      Promise.all([unlistenDragEnter, unlistenDragLeave, unlistenDragDrop]).then(
        ([ue, ul, ud]) => {
          ue();
          ul();
          ud();
        },
      );
    };
  }, []);

  // Browser visual test harness — accessed via ?test=diff
  const searchParams = new URLSearchParams(window.location.search);
  const testMode = searchParams.get('test');
  const demoMode = searchParams.get('demo');

  if (testMode === 'diff') {
    return (
      <main className="app-shell">
        <BrowserTestHarness />
      </main>
    );
  }

  // Demo gallery — accessed via ?demo=gallery
  if (demoMode === 'gallery') {
    return (
      <SettingsProvider>
        <DemoGallery />
      </SettingsProvider>
    );
  }

  // Welcome / landing page — accessed via ?demo=welcome
  if (demoMode === 'welcome') {
    return (
      <main className="app-shell">
        <aside className="sidebar">
          <div className="brand">
            <SplitSquareHorizontal size={20} />
            <span>Diff Tool</span>
          </div>
          <nav className="mode-list" aria-label="Comparison modes">
            <button className="active"><GitBranch size={16} /> Changes</button>
            <button><Layers3 size={16} /> Folders</button>
            <button><Image size={16} /> Images</button>
            <button><TerminalSquare size={16} /> CLI</button>
          </nav>
        </aside>
        <section className="workspace" aria-label="Diff workspace">
          <WelcomeHero />
        </section>
      </main>
    );
  }

  // CLI-backed render test — accessed via ?test=cli-smoke
  if (testMode === 'cli-smoke') {
    return (
      <main className="app-shell">
        <CliSmokeTestPage />
      </main>
    );
  }

  // Desktop render smoke test — accessed via ?test=smoke
  if (testMode === 'smoke') {
    return (
      <main className="app-shell">
        <article className="smoke-test-page" aria-label="Desktop render smoke test">
          <header className="smoke-header">
            <h1>Desktop Render Smoke Test</h1>
            <p>Fixture: examples/text-basic</p>
            <div className="smoke-stats">
              <span className="smoke-stat" data-testid="smoke-additions">+{TEXT_BASIC_DIFF.stats.additions}</span>
              <span className="smoke-stat" data-testid="smoke-deletions">−{TEXT_BASIC_DIFF.stats.deletions}</span>
              <span className="smoke-stat" data-testid="smoke-unchanged">
                {TEXT_BASIC_DIFF.stats.unchanged} unchanged
              </span>
            </div>
          </header>
          <NativeDiffRenderer diff={TEXT_BASIC_DIFF} />
        </article>
      </main>
    );
  }

  // Progress bar simulation test — accessed via ?test=progress
  if (testMode === 'progress') {
    return (
      <SettingsProvider>
        <ProgressTestPage />
      </SettingsProvider>
    );
  }

  // AI chat test — accessed via ?test=ai
  if (testMode === 'ai') {
    return <AiTestPage />;
  }

  // Office document diff test — accessed via ?test=office
  if (testMode === 'office') {
    return <OfficeTestPage />;
  }

  const { state: loadState, stats, nativeDiff, retry, diffProgress } = useFileDiffLoader(leftPath, rightPath);

  const fileDiff = useMemo(
    () => (loadState.phase === 'loaded' ? loadState.fileDiff ?? null : null),
    [loadState],
  );

  const treeEntries = useTreeLoader(rootPath);

  const basename = (p: string) => p.split('/').pop() ?? p;

  const handleTreeSelect = (path: string) => {
    setActivePath(path);
    setRightPath(path);
    setLeftPath(undefined);
  };

  const handleSetLeft = useCallback((path: string) => {
    setLeftPath(path);
    setActivePath(undefined);
  }, []);

  const handleSetRight = useCallback((path: string) => {
    setRightPath(path);
    setActivePath(undefined);
  }, []);

  const handleOpenLeft = useCallback(async () => {
    if (!isTauri) return;
    const p = await openFileDialog();
    if (p !== null) {
      setLeftPath(p);
      setActivePath(undefined);
    }
  }, []);

  const handleOpenRight = useCallback(async () => {
    if (!isTauri) return;
    const p = await openFileDialog();
    if (p !== null) {
      setRightPath(p);
      setActivePath(undefined);
    }
  }, []);

  const handleOpenFolder = useCallback(async () => {
    if (!isTauri) return;
    const p = await openFolderDialog();
    if (p !== null) {
      setRootPath(p);
      setActivePath(undefined);
    }
  }, []);

  return (
    <>
      {dropOverlay && (
        <div
          className="drop-overlay"
          aria-label="Drop files or folders to compare"
        >
          <div className="drop-overlay-card">
            <FolderOpen size={48} className="drop-overlay-icon" />
            <h2 className="drop-overlay-title">Drop to compare</h2>
            <p className="drop-overlay-hint">
              Files → compare left/right &nbsp;·&nbsp; Folder → scan tree
            </p>
          </div>
        </div>
      )}
    <main className="app-shell">
      <aside className="sidebar">
        <div className="brand">
          <SplitSquareHorizontal size={20} />
          <span>Diff Tool</span>
        </div>
        <nav className="mode-list" aria-label="Comparison modes">
          <button className="active"><GitBranch size={16} /> Changes</button>
          <button><Layers3 size={16} /> Folders</button>
          <button><Image size={16} /> Images</button>
          <button><TerminalSquare size={16} /> CLI</button>
        </nav>
        {isTauri && (
          <button className="tree-open-folder-btn" onClick={handleOpenFolder} title="Open folder to scan">
            <FolderOpen size={15} />
            <span className="tree-open-folder-label">
              {rootPath
                ? rootPath.split('/').pop() ?? rootPath
                : 'Open folder...'}
            </span>
          </button>
        )}
        <FileTreePane
          entries={treeEntries}
          activePath={activePath}
          leftPath={leftPath}
          rightPath={rightPath}
          onSelect={handleTreeSelect}
          onSetLeft={handleSetLeft}
          onSetRight={handleSetRight}
        />
      </aside>
      <section className="workspace" aria-label="Diff workspace">
        <header className="toolbar">
          <div>
            <h1>Working Tree</h1>
            <div className="toolbar-file-picker">
              <button className="toolbar-open-btn" onClick={handleOpenLeft} title="Open left file (original)">
                <FileMinus2 size={14} />
                <span className="toolbar-open-label">
                  {leftPath ? basename(leftPath) : 'Open left...'}
                </span>
              </button>
              <button className="toolbar-open-btn" onClick={handleOpenRight} title="Open right file (changed)">
                <FilePlus2 size={14} />
                <span className="toolbar-open-label">
                  {rightPath ? basename(rightPath) : 'Open right...'}
                </span>
              </button>
              {!isTauri && (
                <a href="/?demo=gallery" className="toolbar-open-btn" title="Explore live diff examples">
                  <Play size={14} />
                  <span className="toolbar-open-label">Live examples</span>
                </a>
              )}
            </div>
            <div className="toolbar-stats">
              <span className="toolbar-stat toolbar-stat-add">
                +{stats.additions}
              </span>
              <span className="toolbar-stat toolbar-stat-del">
                −{stats.deletions}
              </span>
            </div>
          </div>
          <div className="toolbar-actions">
            <button
              className={settings.diffStyle === 'unified' ? 'active' : ''}
              onClick={() => updateSetting('diffStyle', 'unified')}
            >
              Unified
            </button>
            <button
              className={settings.diffStyle === 'split' ? 'active' : ''}
              onClick={() => updateSetting('diffStyle', 'split')}
            >
              Split
            </button>
            <SettingsPanel />
          </div>
        </header>
        {loadState.phase === 'idle' ? (
          <article className="diff-pane" aria-label="Welcome">
            <WelcomeHero onExplore={() => window.location.href = '/?demo=gallery'} />
          </article>
        ) : (
          <DiffPane
            fileDiff={fileDiff}
            nativeDiff={nativeDiff}
            loadState={loadState}
            onRetry={retry}
            diffProgress={diffProgress}
          />
        )}
      </section>
    </main>
    </>
  );
}

// ── CLI-backed smoke test page ──────────────────────────────────────────

function CliSmokeTestPage() {
  const [state, setState] = useState<'loading' | 'error' | 'loaded'>('loading');
  const [errorMsg, setErrorMsg] = useState('');
  const [diff, setDiff] = useState<DiffResult | null>(null);

  useEffect(() => {
    let cancelled = false;
    async function load() {
      try {
        const resp = await fetch('/cli-fixture.json');
        if (!resp.ok) throw new Error(`HTTP ${resp.status}: ${resp.statusText}`);
        const json: DiffResult = await resp.json();
        if (!cancelled) {
          setDiff(json);
          setState('loaded');
        }
      } catch (err) {
        if (!cancelled) {
          setErrorMsg(err instanceof Error ? err.message : String(err));
          setState('error');
        }
      }
    }
    load();
    return () => { cancelled = true; };
  }, []);

  if (state === 'loading') {
    return (
      <article className="smoke-test-page" aria-label="CLI-backed render smoke test">
        <header className="smoke-header">
          <h1>CLI-Backed Render Smoke Test</h1>
          <p className="smoke-loading" data-testid="cli-smoke-loading">Loading CLI fixture…</p>
        </header>
      </article>
    );
  }

  if (state === 'error') {
    return (
      <article className="smoke-test-page" aria-label="CLI-backed render smoke test">
        <header className="smoke-header">
          <h1>CLI-Backed Render Smoke Test</h1>
          <p className="smoke-error" data-testid="cli-smoke-error">{errorMsg}</p>
        </header>
      </article>
    );
  }

  return (
    <article className="smoke-test-page" aria-label="CLI-backed render smoke test">
      <header className="smoke-header">
        <h1>CLI-Backed Render Smoke Test</h1>
        <p>Fixture: {diff?.files[0]?.left} → {diff?.files[0]?.right}</p>
        <div className="smoke-stats">
          <span className="smoke-stat" data-testid="cli-smoke-additions">+{diff?.stats?.additions}</span>
          <span className="smoke-stat" data-testid="cli-smoke-deletions">−{diff?.stats?.deletions}</span>
          <span className="smoke-stat" data-testid="cli-smoke-unchanged">
            {diff?.stats?.unchanged} unchanged
          </span>
        </div>
      </header>
      {diff && <NativeDiffRenderer diff={diff} />}
    </article>
  );
}

// ── Progress bar simulation test page ───────────────────────────────────

const PROGRESS_STAGES: Array<{
  stage: DiffProgress['stage'];
  path?: string;
  bytes?: number;
  delayMs: number;
}> = [
  { stage: 'reading', path: 'examples/text-basic/left.txt', bytes: 17, delayMs: 400 },
  { stage: 'reading', path: 'examples/text-basic/right.txt', bytes: 22, delayMs: 400 },
  { stage: 'normalizing', delayMs: 500 },
  { stage: 'computing_diff', delayMs: 600 },
  { stage: 'computing_intraline_spans', delayMs: 400 },
  { stage: 'building_hunks', delayMs: 500 },
];

function ProgressTestPage() {
  const [phase, setPhase] = useState<'loading' | 'loaded'>('loading');
  const [progressIndex, setProgressIndex] = useState(-1);

  useEffect(() => {
    let cancelled = false;
    let timeout: ReturnType<typeof setTimeout>;

    async function simulate() {
      // Small delay to ensure the initial "loading without progress" state is visible
      await new Promise((r) => { timeout = setTimeout(r, 300); });
      if (cancelled) return;
      setProgressIndex(0);

      for (let i = 0; i < PROGRESS_STAGES.length; i++) {
        await new Promise((r) => { timeout = setTimeout(r, PROGRESS_STAGES[i].delayMs); });
        if (cancelled) return;
        setProgressIndex(i + 1);
      }

      // Small pause on the last stage before transitioning to loaded
      await new Promise((r) => { timeout = setTimeout(r, 300); });
      if (cancelled) return;
      setPhase('loaded');
    }

    simulate();
    return () => {
      cancelled = true;
      clearTimeout(timeout);
    };
  }, []);

  const currentProgress: DiffProgress | null =
    phase === 'loading' && progressIndex >= 0 && progressIndex < PROGRESS_STAGES.length
      ? {
          stage: PROGRESS_STAGES[progressIndex].stage,
          path: PROGRESS_STAGES[progressIndex].path,
          bytes: PROGRESS_STAGES[progressIndex].bytes,
        }
      : null;

  return (
    <main className="app-shell">
      <section className="workspace" aria-label="Progress test workspace">
        <header className="smoke-header">
          <h1>Progress Bar Simulation Test</h1>
          <p data-testid="progress-phase">
            {phase === 'loading'
              ? `Stage: ${currentProgress?.stage ?? 'initializing'}`
              : 'Done'}
          </p>
        </header>
        {phase === 'loading' ? (
          <DiffPane
            fileDiff={null}
            nativeDiff={null}
            loadState={{ phase: 'loading' }}
            onRetry={() => {}}
            diffProgress={currentProgress}
          />
        ) : (
          <>
            <div className="smoke-stats" style={{ padding: '14px 20px' }}>
              <span className="smoke-stat" data-testid="progress-additions">+{TEXT_BASIC_DIFF.stats.additions}</span>
              <span className="smoke-stat" data-testid="progress-deletions">−{TEXT_BASIC_DIFF.stats.deletions}</span>
            </div>
            <NativeDiffRenderer diff={TEXT_BASIC_DIFF} />
          </>
        )}
      </section>
    </main>
  );
}

